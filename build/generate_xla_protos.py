def described(root: str, protos) -> bytes:
  """`protos` under `root` and their imports, one serialized FileDescriptorSet (protoc's)."""
  import grpc_tools
  from grpc_tools import protoc

  with tempfile.TemporaryDirectory() as work:
    out = os.path.join(work, "set.pb")
    include = os.path.join(os.path.dirname(grpc_tools.__file__), "_proto")
    if protoc.main(["protoc", f"-I{root}", f"-I{include}", "--include_imports",
                    f"--descriptor_set_out={out}", *protos]):
      sys.exit("protoc failed")
    with open(out, "rb") as f:
      return f.read()


def _write(name: str, doc: str, constants: str, data: bytes) -> None:
  body = "\n".join(f'    "{line}"' for line in textwrap.wrap(data.hex(), 100))
  with open(os.path.join(ROOT, "jax", "_src", name), "w") as out:
    out.write(f'''{LICENSE}"""{doc}

Generated by build/generate_xla_protos.py; do not edit.
"""
{constants}
FILE_DESCRIPTOR_SET = bytes.fromhex(
{body}
)
''')


def main() -> None:
  commit = pinned_xla()
  with tempfile.TemporaryDirectory() as work:
    for path in PROTOS:
      os.makedirs(os.path.join(work, os.path.dirname(path)), exist_ok=True)
      url = f"https://raw.githubusercontent.com/openxla/xla/{commit}/{path}"
      with urllib.request.urlopen(url) as source, open(os.path.join(work, path), "wb") as out:
        out.write(source.read())
    data = described(work, PROTOS)
  _write("xla_protos.py",
         f"XLA's {', '.join(PROTOS)} and their imports at XLA {commit}, one serialized FileDescriptorSet.",
         f'\nXLA_COMMIT = "{commit}"\n', data)
  _write("mosaic_gpu_protos.py",
         f"Mosaic GPU's kernel record ({MOSAIC_GPU_PROTO}, the file the CUDA plugin is built from), one\n"
         "serialized FileDescriptorSet.", "", described(ROOT, [MOSAIC_GPU_PROTO]))


if __name__ == "__main__":
  main()
