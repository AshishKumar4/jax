"""Writes jax/_src/xla_protos.py: XLA's hlo.proto and what it imports, at the XLA commit MODULE.bazel pins, as one
serialized FileDescriptorSet, which jax._src.hlo_reader reads compiled modules through.

  python build/generate_xla_protos.py

Needs grpcio-tools (its protoc) and the network (the protos are fetched from openxla/xla at the pinned commit).
Rerun whenever MODULE.bazel's XLA commit moves; the module states the commit it was written at.
"""

import os
import re
import sys
import tempfile
import textwrap
import urllib.request

PROTOS = ("xla/xla_data.proto", "xla/service/metrics.proto", "xla/service/hlo.proto")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pinned_xla() -> str:
  with open(os.path.join(ROOT, "MODULE.bazel")) as f:
    module = f.read()
  match = re.search(r'module_name = "xla",.*?strip_prefix = "xla-([0-9a-f]{40})"', module, re.S)
  if match is None:
    sys.exit("MODULE.bazel pins no XLA commit")
  return match.group(1)


def main() -> None:
  import grpc_tools
  from grpc_tools import protoc

  commit = pinned_xla()
  with tempfile.TemporaryDirectory() as work:
    for path in PROTOS:
      os.makedirs(os.path.join(work, os.path.dirname(path)), exist_ok=True)
      url = f"https://raw.githubusercontent.com/openxla/xla/{commit}/{path}"
      with urllib.request.urlopen(url) as source, open(os.path.join(work, path), "wb") as out:
        out.write(source.read())
    described = os.path.join(work, "set.pb")
    include = os.path.join(os.path.dirname(grpc_tools.__file__), "_proto")
    if protoc.main(["protoc", f"-I{work}", f"-I{include}", "--include_imports",
                    f"--descriptor_set_out={described}", *PROTOS]):
      sys.exit("protoc failed")
    with open(described, "rb") as f:
      data = f.read()
  lines = textwrap.wrap(data.hex(), 100)
  body = "\n".join(f'    "{line}"' for line in lines)
  with open(os.path.join(ROOT, "jax", "_src", "xla_protos.py"), "w") as out:
    out.write(f'''# Copyright 2026 The JAX Authors.
#
# Licensed under the Apache License, Version 2.0 (the "License");
# you may not use this file except in compliance with the License.
# You may obtain a copy of the License at
#
#     https://www.apache.org/licenses/LICENSE-2.0
#
# Unless required by applicable law or agreed to in writing, software
# distributed under the License is distributed on an "AS IS" BASIS,
# WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
# See the License for the specific language governing permissions and
# limitations under the License.
"""XLA's {", ".join(PROTOS)} and their imports at XLA {commit}, one serialized FileDescriptorSet.

Generated by build/generate_xla_protos.py; do not edit.
"""

XLA_COMMIT = "{commit}"

FILE_DESCRIPTOR_SET = bytes.fromhex(
{body}
)
''')


if __name__ == "__main__":
  main()
