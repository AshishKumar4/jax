"""Writes the schemas jax reads serialized records through, each one serialized FileDescriptorSet:
jax/_src/xla_protos.py, XLA's hlo.proto and what it imports at the XLA commit MODULE.bazel pins, which
jax._src.hlo_reader reads compiled modules through; jax/_src/mosaic_gpu_protos.py, Mosaic GPU's kernel record
(jaxlib/mosaic/gpu/mosaic_gpu.proto, the file the CUDA plugin is built from), which
jax._src.mosaic_gpu_records reads a compiled kernel's record through.

  python build/generate_xla_protos.py

Needs grpcio-tools (its protoc) and the network (XLA's protos are fetched from openxla/xla at the pinned
commit). Rerun whenever MODULE.bazel's XLA commit moves or mosaic_gpu.proto changes; each module states its
source, and tests/mosaic_gpu_records_test.py fails where the Mosaic one no longer describes the .proto.
"""

import os
import re
import sys
import tempfile
import textwrap
import urllib.request

PROTOS = ("xla/xla_data.proto", "xla/service/metrics.proto", "xla/service/hlo.proto")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def pinned_xla() -> str:
  with open(os.path.join(ROOT, "MODULE.bazel")) as f:
    module = f.read()
  match = re.search(r'module_name = "xla",.*?strip_prefix = "xla-([0-9a-f]{40})"', module, re.S)
  if match is None:
    sys.exit("MODULE.bazel pins no XLA commit")
  return match.group(1)


MOSAIC_GPU_PROTO = "jaxlib/mosaic/gpu/mosaic_gpu.proto"

